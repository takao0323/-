def handle_column_menu(line_bot_api, event):
    """
    コラムメニューがタップされた時の処理
    """
    # 今日の曜日を取得（0=月曜）
    weekday = datetime.now().weekday()

    # 曜日に対応するコラムをランダムに選択
    columns = COLUMN_CONTENTS.get(weekday, COLUMN_CONTENTS[0])
    column_text = random.choice(columns)

    # クイックリプライでアーカイブへのリンクを追加
    quick_reply = QuickReply(items=[
        QuickReplyButton(action=MessageAction(label="📊 今日の体重を記録", text="①今日の体重")),
        QuickReplyButton(action=MessageAction(label="🍽 今日の食事を記録", text="②今日の食事")),
        QuickReplyButton(action=MessageAction(label="🤝 コミュニティへ", text="⑤交流の場"))
    ])

    line_bot_api.reply_message(
        event.reply_token,
        TextSendMessage(text=column_text, quick_reply=quick_reply)
    )


def send_daily_column(line_bot_api, user_ids):
    """
    毎日20:00にコラムを配信
    APSchedulerから呼び出される

    Args:
        line_bot_api: LINE Bot API インスタンス
        user_ids: ユーザーIDのリスト
    """
    weekday = datetime.now().weekday()
    columns = COLUMN_CONTENTS.get(weekday, COLUMN_CONTENTS[0])
    column_text = random.choice(columns)

    for user_id in user_ids:
        try:
            line_bot_api.push_message(
                user_id,
                TextSendMessage(text=column_text)
            )
        except Exception as e:
            print(f"Error sending column to {user_id}: {e}")


def get_column_for_date(date):
    """
    指定日のコラムを取得（テスト用）

    Args:
        date: datetime object

    Returns:
        str: コラム本文
    """
    weekday = date.weekday()
    columns = COLUMN_CONTENTS.get(weekday, COLUMN_CONTENTS[0])
    return random.choice(columns)
